// What scripts/prepare-chatgpt-site.mjs copies into the edge function. The
// edge function imports the same modules as the local server; nothing is
// rewritten, so a change to the server cannot silently produce a wrong copy.
import { readFileSync } from 'node:fs';
import path from 'node:path';

export const EDGE_DIR = 'supabase/functions/siris-manager';

// Source files copied with the same relative paths.
export const EDGE_FILES = [
  'admin.mjs',
  'filters.mjs',
  'formula-parser.mjs',
  'formula-sync.mjs',
  'lookup-store.mjs',
  'lookup-sync.mjs',
  'server-cache.mjs',
  'schema.json',
  'server/app.mjs',
  'server/config.mjs',
  'server/context.mjs',
  'server/edge.mjs',
  'server/http.mjs',
  'server/static.mjs',
  'server/routes/formula.mjs',
  'server/routes/lookup.mjs',
  'server/routes/meta.mjs',
  'server/routes/schema.mjs',
  'server/routes/table.mjs',
];

// Generated files from older versions of the script that are no longer used.
export const STALE_EDGE_FILES = ['materialized-lookup.mjs'];

// The function's backend module: the shared handler with edge settings.
export const EDGE_BACKEND = `// Generated by scripts/prepare-chatgpt-site.mjs; edit server/ instead.
import schema from './schema.json' with { type: 'json' };
import { createEdgeHandler } from './server/edge.mjs';

export const handler = await createEdgeHandler(Deno.env.toObject(), schema);
`;

// Relative imports of a module, e.g. "../admin.mjs".
export function relativeImports(source) {
  return [...source.matchAll(/(?:^|\n)\s*import[^'"]*['"](\.{1,2}\/[^'"]+)['"]/g)].map(match => match[1]);
}

// Every relative import of a copied file must itself be copied, otherwise
// the deployed function fails to start. Returns the missing paths.
export function missingEdgeImports(root = '.') {
  const listed = new Set(EDGE_FILES),
    missing = [];
  for (const file of EDGE_FILES.filter(f => f.endsWith('.mjs'))) {
    const source = readFileSync(path.join(root, file), 'utf8');
    for (const target of relativeImports(source)) {
      const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(file), target));
      if (!listed.has(resolved)) missing.push(`${file} → ${resolved}`);
    }
  }
  return missing;
}
